#!/usr/bin/env python3
"""Make the pitching motion from CMU mocap (mocap.cs.cmu.edu, free for commercial use) for the chibi pitchers.
  curl -sSLO https://raw.githubusercontent.com/una-dinosauria/cmu-mocap/master/data/124/124_01.bvh
  python3 tools/bvh-joints.py 124_01.bvh > p01.json
  python3 tools/make-motion.py p01.json > src/js/03-motion.js
Time warp: k 0..1 = leg lift start .. release, k 1..1.35 = 0.5 s of follow-through (same k as pitcherK in 09-main).
Chibi fit: legs pulled in horizontally (LEG_H), arms shortened (ARM), so the stride and reach suit short legs and big heads."""
import sys, json, math
import numpy as np
d = json.load(open(sys.argv[1])); F = np.array(d['frames'], dtype=float); fps = d['fps']
N = d['names']; ix = {k: i for i, k in enumerate(N)}
SC = 0.98 / F[20, ix['pelvis'], 1]          # standing pelvis height -> 0.98 m (the human scale pitcherJR used)
F *= SC
v = np.linalg.norm(np.diff(F[:, ix['hR']], axis=0), axis=1) * fps
rel = int(np.argmax(v[5:])) + 6
fy = F[:, ix['fL'], 1]; base = np.median(fy[:rel - 150]) if rel > 200 else fy[:20].min()
top = rel - 120 + int(np.argmax(fy[rel - 120:rel]))
st = top
while st > 0 and fy[st] > base + 0.03: st -= 1
st = max(0, st - 10)
end = min(len(F) - 1, rel + int(0.5 * fps))
# yaw: from the start pelvis to the landing foot = +z
p0 = F[st, ix['pelvis']].copy(); land = F[rel, ix['fL']]
ang = math.atan2(land[0] - p0[0], land[2] - p0[2])
c, s = math.cos(-ang), math.sin(-ang)
def tr(p):
    x, y, z = p[0] - p0[0], p[1], p[2] - p0[2]
    return np.array([x * c + z * s, y, -x * s + z * c])
ground = min(F[st, ix['fL'], 1], F[st, ix['fR'], 1])
LEG_H, ARM = 0.62, 0.8
STEP = 0.025; ks = np.arange(0, 1.35 + 1e-9, STEP)
out = []
for k in ks:
    t = st + (rel - st) * k if k <= 1 else rel + (end - rel) * (k - 1) / 0.35
    i0 = int(math.floor(t)); a = t - i0; i1 = min(i0 + 1, len(F) - 1)
    J = {n: tr(F[i0, ix[n]] * (1 - a) + F[i1, ix[n]] * a) for n in N}
    for n in J: J[n][1] -= ground
    P = J['pelvis']
    for n in ['hipL', 'hipR', 'kL', 'kR', 'fL', 'fR']:          # pull the legs in under the body
        J[n][0] = P[0] + (J[n][0] - P[0]) * LEG_H; J[n][2] = P[2] + (J[n][2] - P[2]) * LEG_H
    for sd in 'LR':                                               # shorter arms
        sh = J['s' + sd]
        J['e' + sd] = sh + (J['e' + sd] - sh) * ARM; J['h' + sd] = sh + (J['h' + sd] - sh) * ARM
    for n in ['fL', 'fR']: J[n][1] = max(0.0, J[n][1])
    out += [round(float(x), 3) for n in N for x in J[n]]
print('/* ===== pitching motion from motion capture (CMU Graphics Lab Motion Capture Database, mocap.cs.cmu.edu, subject 124 "Baseball Pitch";')
print('   created with funding from NSF EIA-0196217). Generated by tools/make-motion.py — do not edit by hand.')
print(f'   joint order: {",".join(N)} (x,y,z each, metres, pitcher at the origin facing +z). k step {STEP}. ===== */')
print(f'const PITCH_MO = {{ step: {STEP}, n: {len(ks)}, d: {json.dumps(out, separators=(",", ":"))} }};')
sys.stderr.write(f'frames start {st} top {top} release {rel} end {end}; scale {SC:.4f}; yaw {math.degrees(ang):.1f} deg; samples {len(ks)}\n')
