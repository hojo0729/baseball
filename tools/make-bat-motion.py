#!/usr/bin/env python3
"""Batter body motion from CMU mocap (mocap.cs.cmu.edu, free for commercial use): 124_07 Baseball Swing, 124_08 Baseball Bunt.
  python3 tools/bvh-joints.py 124_07.bvh > p07.json ; python3 tools/bvh-joints.py 124_08.bvh > p08.json
  python3 tools/make-bat-motion.py p07.json p08.json > src/js/03-motion-bat.js
Only the body (pelvis, neck, head, shoulders, hips, knees, feet) comes from the capture; the hands and the bat stay
on the game's swing plan so the bat still meets the spot the player tapped.
Frames of 124_07: stance 250, stride 274-316 (front foot up and down), swing 316 -> contact 336 -> finish 390."""
import sys, json, math
import numpy as np
BODY = ['pelvis', 'neck', 'head', 'sL', 'sR', 'hipL', 'hipR', 'kL', 'kR', 'fL', 'fR']
LEG_H = 0.62
def load(p):
    d = json.load(open(p)); F = np.array(d['frames'], dtype=float); ix = {k: i for i, k in enumerate(d['names'])}
    return F, ix
def frame_fn(F, ix, stance):
    sc = 0.95 / F[stance, ix['pelvis'], 1]
    p0 = F[stance, ix['pelvis']] * sc
    fwd = (F[stance, ix['fL']] - F[stance, ix['fR']]) * sc; fwd[1] = 0; fwd /= np.linalg.norm(fwd)   # back foot -> front foot = toward the pitcher
    ang = math.atan2(fwd[0], fwd[2])            # rotate so that direction becomes -z
    rot = math.pi - ang; c, s = math.cos(rot), math.sin(rot)
    ground = min(F[stance, ix['fL'], 1], F[stance, ix['fR'], 1]) * sc
    def get(f):
        J = {}
        for n in BODY:
            q = F[f, ix[n]] * sc - p0
            x, z = q[0] * c + q[2] * s, -q[0] * s + q[2] * c
            J[n] = np.array([x, q[1] + p0[1] - ground, z])
        P = J['pelvis']
        for n in ['hipL', 'hipR', 'kL', 'kR', 'fL', 'fR']:
            J[n][0] = P[0] + (J[n][0] - P[0]) * LEG_H; J[n][2] = P[2] + (J[n][2] - P[2]) * LEG_H
        for n in ['fL', 'fR']: J[n][1] = max(0.0, J[n][1])
        return J
    return get
F, ix = load(sys.argv[1]); get = frame_fn(F, ix, 250)
J0 = get(250)
# facing check: the chest must face +x (toward the plate) for a right-handed batter
chest = np.cross(J0['sL'] - J0['sR'], np.array([0, 1, 0]))
sys.stderr.write(f'chest dir {chest.round(2)} (want +x); front foot z {J0["fL"][2]:.2f} back {J0["fR"][2]:.2f}\n')
frames = list(range(250, 392, 2))
out = []
for f in frames:
    J = get(f); out += [round(float(v), 3) for n in BODY for v in J[n]]
Fb, ixb = load(sys.argv[2]); getb = frame_fn(Fb, ixb, 200)
B = getb(290); bunt = [round(float(v), 3) for n in BODY for v in B[n]]
print('/* ===== batter body motion from motion capture (CMU Graphics Lab Motion Capture Database, mocap.cs.cmu.edu, subject 124')
print('   "Baseball Swing" / "Baseball Bunt"; created with funding from NSF EIA-0196217). Generated by tools/make-bat-motion.py — do not edit.')
print(f'   joints: {",".join(BODY)}; right-handed batter, pelvis at the origin, facing +x, pitcher toward -z.')
print('   frames: 124_07 #250..#390 every 2nd (120 fps -> 60 fps). i 0 stance, 12 stride starts, 33 swing starts, 43 contact, 70 finish. ===== */')
print(f'const BAT_MO = {{ n: {len(frames)}, d: {json.dumps(out, separators=(",", ":"))}, bunt: {json.dumps(bunt, separators=(",", ":"))} }};')
